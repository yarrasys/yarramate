#!/usr/bin/env node
// Regenerates src/archimate-relationships.generated.ts from the vendored
// ArchiMate 3.2 relationship table (vendor/archi/relationships.xml, MIT).
//
// The generated module is the one source of truth `check` validates
// relationship endpoints against (ADR 0097). It is committed so that the
// runtime never reads the XML and carries no imports at all: the same
// Worker-safety argument as src/shipped-profile.ts. A test re-runs this
// generator against the vendored XML and fails on any byte of drift, so the
// committed module cannot silently fall behind the table it claims to encode.
//
// Usage: node scripts/generate-archimate-relationships.mjs
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const SOURCE = new URL('../vendor/archi/relationships.xml', import.meta.url)
const TARGET = new URL(
  '../src/archimate-relationships.generated.ts',
  import.meta.url,
)

/**
 * Archi's single-letter codes, in the order the XML uses them. The mapping to
 * yarramate relationship kind ids is fixed here and pinned by test.
 */
export const RELATIONSHIP_LETTERS = {
  a: 'access',
  c: 'composition',
  f: 'flow',
  g: 'aggregation',
  i: 'assignment',
  n: 'influence',
  o: 'association',
  r: 'realization',
  s: 'specialization',
  t: 'triggering',
  v: 'serving',
}

/**
 * Archi names one `Junction` row and column; yarramate keeps two junction
 * kinds. Both expand to identical rows and columns. `Relationship` (ArchiMate
 * 3.x relationship-to-relationship) is outside yarramate's model and dropped.
 */
const EXPAND = { Junction: ['andJunction', 'orJunction'] }
const DROP = new Set(['Relationship'])

const toKindId = (archiName) =>
  archiName.charAt(0).toLowerCase() + archiName.slice(1)

/**
 * Parse Archi's relationships.xml into `{ order, rows }` where `order` is the
 * yarramate kind id sequence (XML source order, junction expanded last) and
 * `rows[from][to]` is the permitted letter string for that ordered pair.
 */
export const parseRelationshipsXml = (xml) => {
  const versionMatch = xml.match(/<relationships version="([^"]+)"/)
  if (!versionMatch) throw new Error('relationships.xml carries no version')
  const version = versionMatch[1]

  const archiRows = new Map()
  let current = null
  for (const line of xml.split('\n')) {
    const source = line.match(/<source concept="([A-Za-z]+)"/)
    if (source) {
      current = source[1]
      archiRows.set(current, new Map())
      continue
    }
    const target = line.match(
      /<target concept="([A-Za-z]+)" relations="([a-z]*)"/,
    )
    if (target && current !== null) {
      archiRows.get(current).set(target[1], target[2])
    }
  }

  const expand = (archiName) =>
    DROP.has(archiName)
      ? []
      : (EXPAND[archiName] ?? [toKindId(archiName)])

  const order = []
  for (const archiName of archiRows.keys()) order.push(...expand(archiName))

  const rows = {}
  for (const [archiFrom, targets] of archiRows) {
    for (const from of expand(archiFrom)) {
      const row = {}
      for (const [archiTo, letters] of targets) {
        for (const to of expand(archiTo)) row[to] = letters
      }
      rows[from] = row
    }
  }

  for (const from of order) {
    for (const to of order) {
      if (rows[from]?.[to] === undefined) {
        throw new Error(`relationships.xml has no cell for ${from} -> ${to}`)
      }
      for (const letter of rows[from][to]) {
        if (!(letter in RELATIONSHIP_LETTERS)) {
          throw new Error(`unknown relationship letter "${letter}" at ${from} -> ${to}`)
        }
      }
    }
  }

  return { version, order, rows }
}

const quote = (value) => `'${value}'`

/** Render the generated TypeScript module. Deterministic for a given input. */
export const renderModule = ({ version, order, rows }, sourceSha256) => {
  const lines = []
  lines.push(
    '// GENERATED by scripts/generate-archimate-relationships.mjs from',
    '// vendor/archi/relationships.xml. Do not edit; run `pnpm generate:archimate`.',
    '//',
    '// The ArchiMate 3.2 relationship table (specification Appendix B, including',
    '// derived relationships) as Archi encodes it, re-keyed by yarramate core kind',
    '// id. One row per source kind: a space-separated letter group per target kind',
    '// in CORE_CONCEPT_KIND_ORDER, each letter a permitted relationship kind. This',
    '// module deliberately imports nothing so it can load anywhere the compiler',
    '// loads (ADR 0097).',
    '',
    `export const ARCHIMATE_RELATIONSHIPS_VERSION = ${quote(version)} as const`,
    '',
    `export const ARCHIMATE_RELATIONSHIPS_SOURCE_SHA256 =`,
    `  ${quote(sourceSha256)} as const`,
    '',
    'export const RELATIONSHIP_LETTERS = {',
  )
  for (const [letter, kind] of Object.entries(RELATIONSHIP_LETTERS)) {
    lines.push(`  ${letter}: ${quote(kind)},`)
  }
  lines.push('} as const', '', 'export const CORE_CONCEPT_KIND_ORDER = [')
  for (const kind of order) lines.push(`  ${quote(kind)},`)
  lines.push(
    '] as const',
    '',
    'export type CoreConceptKindId = (typeof CORE_CONCEPT_KIND_ORDER)[number]',
    '',
    '/**',
    ' * Permitted relationship letters per ordered (source, target) kind pair.',
    ' * Index the space-separated groups by CORE_CONCEPT_KIND_ORDER.',
    ' */',
    'export const PERMITTED_RELATIONSHIP_LETTERS: Readonly<',
    '  Record<CoreConceptKindId, string>',
    '> = {',
  )
  for (const from of order) {
    const groups = order.map((to) => rows[from][to] || '-')
    lines.push(`  ${from}:`, `    ${quote(groups.join(' '))},`)
  }
  lines.push('}', '')
  return lines.join('\n')
}

export const generate = () => {
  const xml = readFileSync(SOURCE, 'utf8')
  const sha256 = createHash('sha256').update(xml).digest('hex')
  return renderModule(parseRelationshipsXml(xml), sha256)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TARGET, generate())
  console.log(`wrote ${fileURLToPath(TARGET)}`)
}
